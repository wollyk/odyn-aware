// Phase-13A eval bookkeeping — schema + CRUD.
//
// Why this exists separately from the eval JSONL on the tracker host:
//   the JSONL on disk is the authoritative output (frame-by-frame
//   detections), but the admin UI needs a queryable index of which
//   runs exist, who started them, what config they used, and what the
//   summary said. Putting that in SQLite means we can list 200 runs
//   without scanning 200 JSONLs, and we can survive a tracker restart
//   that wipes the in-memory _runs dict.
//
// One row per eval RUN. Diff results are stored separately in
// eval_diffs (rows keyed by diff_id, foreign-key-ish to two run_ids).
//
// `run_id` and `diff_id` are UUIDs generated by the tracker. We mirror
// them here as the natural key.

/**
 * Apply the evals schema. Idempotent. Wired from openDb().
 */
export function applyEvalsSchema(db) {
  db.exec(`
    CREATE TABLE IF NOT EXISTS eval_runs (
      run_id        TEXT PRIMARY KEY,
      name          TEXT,
      clip          TEXT NOT NULL,
      config_json   TEXT NOT NULL DEFAULT '{}',
      config_hash   TEXT,
      status        TEXT NOT NULL DEFAULT 'running',
      out_path      TEXT,
      summary_json  TEXT,
      header_json   TEXT,
      started_at_ms INTEGER NOT NULL,
      finished_at_ms INTEGER,
      created_by    TEXT,
      inserted_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
      updated_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
    );
    CREATE INDEX IF NOT EXISTS idx_eval_runs_recent
      ON eval_runs(started_at_ms DESC);

    CREATE TABLE IF NOT EXISTS eval_diffs (
      diff_id      TEXT PRIMARY KEY,
      run_a        TEXT NOT NULL,
      run_b        TEXT NOT NULL,
      diff_json    TEXT NOT NULL,
      created_at_ms INTEGER NOT NULL,
      created_by   TEXT,
      inserted_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
    );
    CREATE INDEX IF NOT EXISTS idx_eval_diffs_recent
      ON eval_diffs(created_at_ms DESC);
  `);
}

// ---- runs ---------------------------------------------------------------

/**
 * Record (or upsert) an eval run. `summaryJson` and `headerJson` may be
 * null while the run is still in flight; pass them on subsequent calls
 * once the tracker reports completion. Status transitions:
 *   running -> ok | failed | cancelled
 */
export function upsertEvalRun(
  db,
  {
    runId,
    name,
    clip,
    configJson,
    configHash,
    status,
    outPath,
    summaryJson,
    headerJson,
    startedAtMs,
    finishedAtMs,
    createdBy,
  },
) {
  const stmt = db.prepare(`
    INSERT INTO eval_runs
      (run_id, name, clip, config_json, config_hash, status,
       out_path, summary_json, header_json,
       started_at_ms, finished_at_ms, created_by)
    VALUES
      (@runId, @name, @clip, @configJson, @configHash, @status,
       @outPath, @summaryJson, @headerJson,
       @startedAtMs, @finishedAtMs, @createdBy)
    ON CONFLICT(run_id) DO UPDATE SET
      name          = COALESCE(excluded.name,         eval_runs.name),
      status        = excluded.status,
      summary_json  = COALESCE(excluded.summary_json, eval_runs.summary_json),
      header_json   = COALESCE(excluded.header_json,  eval_runs.header_json),
      finished_at_ms = COALESCE(excluded.finished_at_ms, eval_runs.finished_at_ms),
      updated_at    = strftime('%Y-%m-%dT%H:%M:%fZ','now')
  `);
  stmt.run({
    runId,
    name: name ?? null,
    clip,
    configJson: configJson ?? "{}",
    configHash: configHash ?? null,
    status: status ?? "running",
    outPath: outPath ?? null,
    summaryJson: summaryJson ?? null,
    headerJson: headerJson ?? null,
    startedAtMs,
    finishedAtMs: finishedAtMs ?? null,
    createdBy: createdBy ?? null,
  });
}

export function listEvalRuns(db, { limit = 100 } = {}) {
  const lim = Math.min(Math.max(Number(limit) || 100, 1), 500);
  const rows = db
    .prepare(
      `
      SELECT run_id, name, clip, config_hash, status,
             out_path, summary_json, header_json,
             started_at_ms, finished_at_ms, created_by, updated_at
        FROM eval_runs
       ORDER BY started_at_ms DESC
       LIMIT ?
    `,
    )
    .all(lim);
  return rows.map(parseRunRow);
}

export function getEvalRun(db, runId) {
  const row = db
    .prepare(
      `
      SELECT run_id, name, clip, config_json, config_hash, status,
             out_path, summary_json, header_json,
             started_at_ms, finished_at_ms, created_by, updated_at
        FROM eval_runs WHERE run_id = ?
    `,
    )
    .get(runId);
  return row ? parseRunRow(row) : null;
}

function parseRunRow(row) {
  return {
    run_id: row.run_id,
    name: row.name,
    clip: row.clip,
    config:
      row.config_json !== undefined ? safeJson(row.config_json) : undefined,
    config_hash: row.config_hash,
    status: row.status,
    out_path: row.out_path,
    summary: safeJson(row.summary_json),
    header: safeJson(row.header_json),
    started_at_ms: row.started_at_ms,
    finished_at_ms: row.finished_at_ms,
    created_by: row.created_by,
    updated_at: row.updated_at,
  };
}

function safeJson(s) {
  if (!s) return null;
  try {
    return JSON.parse(s);
  } catch {
    return null;
  }
}

// ---- diffs --------------------------------------------------------------

export function insertEvalDiff(db, { diffId, runA, runB, diffJson, createdBy }) {
  db.prepare(
    `
    INSERT INTO eval_diffs
      (diff_id, run_a, run_b, diff_json, created_at_ms, created_by)
    VALUES (?, ?, ?, ?, ?, ?)
  `,
  ).run(diffId, runA, runB, diffJson, Date.now(), createdBy ?? null);
}

export function listEvalDiffs(db, { limit = 50 } = {}) {
  const lim = Math.min(Math.max(Number(limit) || 50, 1), 200);
  const rows = db
    .prepare(
      `
      SELECT diff_id, run_a, run_b, diff_json, created_at_ms, created_by
        FROM eval_diffs
       ORDER BY created_at_ms DESC
       LIMIT ?
    `,
    )
    .all(lim);
  return rows.map((r) => ({
    diff_id: r.diff_id,
    run_a: r.run_a,
    run_b: r.run_b,
    diff: safeJson(r.diff_json),
    created_at_ms: r.created_at_ms,
    created_by: r.created_by,
  }));
}

export function getEvalDiff(db, diffId) {
  const row = db
    .prepare(
      `
      SELECT diff_id, run_a, run_b, diff_json, created_at_ms, created_by
        FROM eval_diffs WHERE diff_id = ?
    `,
    )
    .get(diffId);
  if (!row) return null;
  return {
    diff_id: row.diff_id,
    run_a: row.run_a,
    run_b: row.run_b,
    diff: safeJson(row.diff_json),
    created_at_ms: row.created_at_ms,
    created_by: row.created_by,
  };
}
